def _sanitize(text: str) -> str:
    """사용자 입력이 프롬프트 태그(<근거>, </질문> 등)를 흉내 내지 못하게 꺾쇠를 바꾼다."""
    return text.replace("<", "‹").replace(">", "›")


def build_context(sources: list[RetrievedChunk]) -> str:
    """검색된 근거를 번호를 붙여 프롬프트용 텍스트로 만든다."""
    blocks = []
    for i, rc in enumerate(sources, start=1):
        blocks.append(f"[근거 {i}] [분야: {rc.chunk.gas_category}] {rc.chunk.citation}\n{rc.chunk.text}")
    return "<근거>\n" + "\n\n".join(blocks) + "\n</근거>"


def build_user_message(question: str, sources: list[RetrievedChunk]) -> str:
    return f"{build_context(sources)}\n\n<질문>\n{_sanitize(question)}\n</질문>"
